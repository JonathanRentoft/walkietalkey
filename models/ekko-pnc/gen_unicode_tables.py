"""Generate crates/ekko-pnc/src/pyunicode.rs: CPython's str semantics that the
reference tool (ekko-stt) relies on, as lookup tables, so the Rust port agrees
with Python character by character instead of with Rust's own Unicode tables.

  str.split()            -> SPACE        (chr(c).isspace())
  str.isalpha()          -> ALPHA        (ranges)
  isupper() or istitle() -> UPPER_OR_TITLE (ranges)
  str.title() on 1 char  -> TITLE        (every char whose title() differs)

Run with the Python that generates the golden set:
    uv run python models/ekko-pnc/gen_unicode_tables.py crates/ekko-pnc/src/pyunicode.rs
"""

from __future__ import annotations

import sys
import unicodedata
from pathlib import Path

MAX = sys.maxunicode + 1


def ranges(pred) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    start = None
    for c in range(MAX):
        if 0xD800 <= c <= 0xDFFF:
            ok = False
        else:
            ok = pred(chr(c))
        if ok and start is None:
            start = c
        elif not ok and start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, MAX - 1))
    return out


def rust_str(s: str) -> str:
    return '"' + "".join(f"\\u{{{ord(ch):x}}}" for ch in s) + '"'


def main() -> int:
    out = Path(sys.argv[1])
    space = [c for c in range(MAX) if not 0xD800 <= c <= 0xDFFF and chr(c).isspace()]
    alpha = ranges(str.isalpha)
    upper = ranges(lambda ch: ch.isupper() or ch.istitle())
    title = [(c, chr(c).title()) for c in range(MAX)
             if not 0xD800 <= c <= 0xDFFF and chr(c).title() != chr(c)]
    lines = [
        "// @generated by models/ekko-pnc/gen_unicode_tables.py. Do not edit.",
        f"// CPython {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}.",
        "",
        f'pub const PYTHON_VERSION: &str = "{sys.version.split()[0]}";',
        f'pub const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";',
        "",
        "/// Code points for which `chr(c).isspace()` is true.",
        "pub static SPACE: &[u32] = &[" + ", ".join(f"0x{c:x}" for c in space) + "];",
        "",
        "/// Inclusive ranges for which `chr(c).isalpha()` is true.",
        "pub static ALPHA: &[(u32, u32)] = &[",
        *[f"    (0x{a:x}, 0x{b:x})," for a, b in alpha],
        "];",
        "",
        "/// Inclusive ranges for which `chr(c).isupper() or chr(c).istitle()` is true.",
        "pub static UPPER_OR_TITLE: &[(u32, u32)] = &[",
        *[f"    (0x{a:x}, 0x{b:x})," for a, b in upper],
        "];",
        "",
        "/// `chr(c).title()` for every code point where it differs from `chr(c)`, sorted.",
        "pub static TITLE: &[(u32, &str)] = &[",
        *[f"    (0x{c:x}, {rust_str(t)})," for c, t in title],
        "];",
        "",
    ]
    out.write_text("\n".join(lines))
    print(f"wrote {out}: {len(space)} space, {len(alpha)} alpha ranges, "
          f"{len(upper)} upper/title ranges, {len(title)} title mappings")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
